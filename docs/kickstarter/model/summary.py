"""Builds out/SUMMARY.md from the model. Imported by piblo_model.main()."""
import piblo_model as pm

money = pm.money

def structures(model, units):
    out = []
    for ps, (po, pf) in pm.PRICE_SETS.items():
        for mn, mf in pm.MIXES.items():
            for en, ed in pm.EB.items():
                for sn, sm in pm.SHIP.items():
                    r = pm.expected_and_downside(model, units, mf, po, pf, ed, sm)
                    out.append(dict(units=units, price_set=ps, mix=mn, eb=en, ship=sn, **r))
    return out

def is_viable(model, s):
    return s["expected"] > 0 and s["downside"] >= -model.env0["viable_max_loss"] and s["funded"]["expected"] > 0.5

def table(headers, rows):
    L = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    L += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(L)

def srow(s):
    return [s["price_set"], s["mix"], s["eb"], s["ship"], money(s["expected"]), money(s["downside"]),
            money(s["np"]["conservative"]), money(s["np"]["expected"]), money(s["np"]["optimistic"]), money(s["cash"]), money(s["goal"])]

SH = ["Prices (Orig/Founder's)", "Mix", "Early bird", "Shipping", "Expected net", "Downside net", "Cons.", "Exp.", "Opt.", "Cash before payout (downside)", "Goal"]

def write_summary(model, path):
    A = model.env0
    L = []
    w = L.append
    ref = dict(n_ref=500, mix_f=0.2, p_o=103, p_f=194)
    w("# Piblo Kickstarter profit model: summary\n")
    w("Generated by `piblo_model.py` from `assumptions.csv`. All figures GBP, **net profit before business tax**, Maz's own time unpaid and not costed. "
      "**Nothing here is a supplier quote.** Every input is tagged QUOTED / SOURCED-LIST-PRICE / ASSUMPTION in `assumptions.csv`; at the time of writing "
      "no input is QUOTED and the Cardputer, Kickstarter fees, BackerKit fees and VAT threshold are the only list-price sourced inputs. Treat every output as a "
      "decision aid for what to quote next, not a forecast.\n")
    w("Definitions: *nominal units* = backers at the baseline prices (GBP 103 / 194) under expected demand; the demand level, price elasticity, early bird and "
      "shipping strategy then move actual backers. *Expected* = probability-weighted over conservative/expected/optimistic demand "
      f"({A['p_cons']:.0%}/{A['p_exp']:.0%}/{A['p_opt']:.0%}, subjective). *Downside* = conservative demand, costs +15%, defects 7.5%, refunds +3pp, one GBP {A['shock_lump']:,.0f} unexpected expense. "
      f"*Viable* = expected net > 0, goal met in the expected case, and downside loss no worse than GBP {A['viable_max_loss']:,.0f}. "
      "All-or-nothing: if pledges miss the goal, the campaign pays nothing and only the pre-launch spend (prototypes, samples, video, legal) plus ads is lost; compliance and tooling are modelled as paid after funding.\n")

    # --- reference table
    w("## 1. Baseline GBP 103 / 194, 80/20 mix, expected demand, shipping charged separately, registered for VAT\n")
    rows = []
    for u in (100, 250, 500, 1000, 5000):
        V = model.run(n_ref=u, mix_f=0.2, p_o=103, p_f=194)
        rows.append([u, int(V["bk_o"]), int(V["bk_f"]), money(V["gross_total"]), money(V["fx_total"]), money(V["np"]),
                     "yes" if V["funded"] > .5 else "NO", money(V["goal"]), money(V["cash_upfront"]), money(pm.peak_negative_cash(V)),
                     f"{V['be_units']:,.0f}", int(V["risk"])])
    w(table(["Nominal units", "Orig", "Fndr", "Gross pledges", "Fixed costs", "Net profit", "Goal met", "Funding goal", "Cash before payout", "Peak negative cash", "Break-even units", "Risk"], rows))
    V500 = model.run(**ref)
    w("")
    w(f"Contribution per backer before fixed costs at 500 nominal: Original {money(V500['cu_o'])}, Founder's {money(V500['cu_f'])} "
      f"(Founder's is thin because CNC cost per unit at ~100 units is ~GBP 55-70). Break-even is where cumulative contribution covers fixed costs of about {money(V500['fx_total']*(1+A['cont_pct']))} including contingency.\n")

    # --- itemised P&L at reference
    w("### Itemised P&L, 500 nominal units, GBP 103/194, 80/20, expected\n")
    items = [("Gross pledges collected (incl UK VAT, shipping charged)", V500["gross_total"]), ("Refunds", -V500["refunds"]), ("Output VAT (UK pledges only)", -V500["vat_net"]),
             ("Kickstarter 5%", -V500["fees_ks"]), ("Payment processing", -V500["fees_proc"]), ("Pledge manager fees", -V500["fees_pm"]), ("Ads/marketing", -V500["ads"]),
             ("Cardputer electronics", -V500["cost_elec"]), ("Enclosures", -V500["cost_encl"]), ("Assembly/QA labour", -V500["cost_labour"]), ("Packaging", -V500["cost_pack"]),
             ("Inbound freight, duty, irrecoverable import VAT", -V500["cost_inbound"]), ("Outbound shipping", -V500["cost_ship_out"]), ("Fulfilment", -V500["cost_fulfil"]),
             ("Support", -V500["cost_support"]), ("Storage", -V500["cost_storage"]), ("Defect replacements", -V500["cost_repl"]),
             ("Fixed: pre-launch (lost if campaign fails)", -V500["fx_pre"]), ("Fixed: post-funding compliance etc", -V500["fx_post"]), ("Fixed: CNC setup / tooling", -V500["fx_order"]),
             ("Irrecoverable VAT on one-offs", -V500["fx_vatcost"]), ("Contingency", -V500["cost_cont"]), ("NET PROFIT before business tax", V500["np"])]
    w(table(["Line", "GBP"], [[a, f"{b:,.0f}"] for a, b in items]))
    w("")

    # --- structures
    for u in (500, 1000):
        S_all = structures(model, u)
        S = [s for s in S_all if s["mix"] in ("80/20", "60/40")]
        viable = [s for s in S if is_viable(model, s)]
        w(f"## {2 if u == 500 else 3}. Reward structures ranked at {u} nominal units\n")
        w(f"{len(viable)} of {len(S)} structures are viable under the definition above.\n")
        pool = viable if len(viable) >= 3 else S
        label = "Top 5 viable by expected net profit" if len(viable) >= 3 else "No/few viable structures: top 5 by expected net profit (NOT viable, shown for direction only)"
        w(f"**{label}**\n")
        w(table(SH, [srow(s) for s in sorted(pool, key=lambda s: -s["expected"])[:5]]))
        w("")
        w("**Top 5 by downside (least bad worst case)**\n")
        w(table(SH, [srow(s) for s in sorted(S, key=lambda s: -s["downside"])[:5]]))
        w("")
        single = sorted([s for s in S_all if s["mix"] not in ("80/20", "60/40")], key=lambda s: -s["expected"])[:3]
        w("For reference, best single-edition structures (not recommended on demand grounds):\n")
        w(table(SH, [srow(s) for s in single]))
        w("")

    # --- price set x mix
    w("## 4. Break-even backers by price set and mix (base costs, shipping charged separately, registered for VAT)\n")
    rows = []
    for ps, (po, pf) in pm.PRICE_SETS.items():
        r = [ps]
        for mn, mf in pm.MIXES.items():
            n = pm.break_even_backers(model, mf, po, pf)
            r.append(f"{n:,}" if n else ">8,000")
        rows.append(r)
    w(table(["Prices"] + list(pm.MIXES), rows))
    w("\nBreak-even here means smallest total backers with net profit above zero AND the funding goal met, so it already includes the all-or-nothing rule.\n")

    # --- shipping and VAT strategies
    w("## 5. Shipping strategy and VAT strategy (500 and 1000 nominal, GBP 103/194, 80/20, expected demand)\n")
    rows = []
    for u in (500, 1000):
        for sn, sm in pm.SHIP.items():
            V = model.run(n_ref=u, mix_f=.2, p_o=103, p_f=194, ship_mode=sm)
            rows.append([u, f"shipping {sn}", int(V["bk_o"] + V["bk_f"]), money(V["gross_total"]), money(V["np"])])
        for vn, vm in (("register voluntarily", 1), ("register only over GBP 90k", 0)):
            V = model.run(n_ref=u, mix_f=.2, p_o=103, p_f=194, vat_mode=vm)
            rows.append([u, f"VAT: {vn}", int(V["bk_o"] + V["bk_f"]), money(V["gross_total"]), money(V["np"])])
    w(table(["Nominal", "Strategy", "Backers", "Gross pledges", "Net profit"], rows))
    w("\nPledge manager is only worth it if the demand boost from a lower headline price outweighs its 2% + 3.5% fees, a second payment fee and non-payment; see the sensitivity to `w_pm`.\n")

    # --- shocks
    w("## 6. Shocks (500 and 1000 nominal, GBP 103/194, 80/20, expected demand)\n")
    rows = []
    for u in (500, 1000):
        base = model.run(n_ref=u, mix_f=.2, p_o=103, p_f=194)["np"]
        rows.append([u, "none", money(base), "-"])
        for sh in pm.SHOCKS:
            V = model.run(n_ref=u, mix_f=.2, p_o=103, p_f=194, **pm.shock_kwargs(A, sh))
            rows.append([u, sh, money(V["np"]), money(V["np"] - base)])
    w(table(["Nominal", "Shock", "Net profit", "Change"], rows))
    w("")

    # --- sensitivity
    base, sens = pm.sensitivity(model, dict(n_ref=1000, mix_f=.2, p_o=103, p_f=194))
    w("## 7. Sensitivity: what moves profit most (1000 nominal, GBP 103/194, 80/20, expected)\n")
    w(f"Base net profit {money(base)}. Each driver moved to its low / high value in `assumptions.csv`, others held.\n")
    w(table(["Driver", "At low", "At high"], [[f"{n} (`{k}`)", f"{lo:+,.0f}", f"{hi:+,.0f}"] for k, n, lo, hi in sens[:12]]))
    w("")

    # --- funding goal
    g = V500
    w("## 8. Recommended funding goal (GBP 103/194, 80/20 mix)\n")
    gross_up = 1 - A["ks_fee_pct"] - A["proc_pct"] - A["ad_pct"] - A["fail_rate"]
    w(table(["Component", "GBP"], [["Fixed one-offs (pre-launch + post-funding + CNC setup), base costs", f"{g['fx_plan']:,.0f}"],
                                    [f"MOQ cash: {A['moq_units']:.0f} units of landed cost (electronics, shells, labour, packaging, freight)", f"{g['moq_cash']:,.0f}"],
                                    [f"Contingency {A['goal_cont']:.0%}", f"{(g['fx_plan'] + g['moq_cash'])*A['goal_cont']:,.0f}"],
                                    [f"Gross-up for Kickstarter 5%, processing 3%, ads {A['ad_pct']:.0%}, failed pledges {A['fail_rate']:.0%} (divide by {gross_up:.3f})", f"{g['goal'] - (g['fx_plan'] + g['moq_cash'])*(1 + A['goal_cont']):,.0f}"],
                                    ["**Funding goal (rounded up to GBP 500)**", f"**{g['goal']:,.0f}**"]]))
    w("")
    w(f"Cash Maz must front **before** the Kickstarter payout (about 14 days after close): pre-launch spend plus ads plus supplier deposits "
      f"(deposit {A['dep_pct']:.0%} of goods + CNC setup) = about {money(g['cash_upfront'])} at 500 nominal and "
      f"{money(model.run(n_ref=1000, mix_f=.2, p_o=103, p_f=194)['cash_upfront'])} at 1,000. If M5Stack is full pre-pay (`dep_pct` = 1.0) it is higher. "
      "Pre-launch spend lost if the campaign misses its goal: "
      f"{money(g['fx_pre'])} plus ads.\n")
    w("Note the goal is a funding threshold, not a profit target: reaching it only covers a first batch and the one-offs. Profit needs several times the goal in backers (section 1).\n")

    w("## 9. How to read this honestly\n")
    w("- The model is internally consistent (checked by `test_model.py`: cash timeline sums to net profit; unit contributions reconcile to totals) but every cost is a list price or an assumption.\n"
      "- Price elasticity (`elast_o`, `elast_f`) and demand scale are untested guesses. With the assumed elasticities, higher prices win because unit margin rises faster than demand falls; "
      "at the elasticity high case that reverses. Run a landing-page price test before trusting any price conclusion.\n"
      "- Below roughly 1,000 backers fixed costs dominate; the project is a bet on volume. Staging spend (video, samples first; compliance after funding) caps what a miss costs.\n"
      "- Excluded: corporation/income tax, Maz's time, FX moves on USD supplier prices, US tariffs on inbound parcels to backers, EU VAT/IOSS handling, chargebacks, rejected-campaign relaunch, retail/store sales after the campaign.\n")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
