"""Turn one character from a lineup image into an RGB565 sprite header for the Cardputer.

Usage: python scripts/char_sprite.py <image> <x0,y0,x1,y1> <height_px> <name> [out.h]
The flat paper background and the soft floor shadow become transparent (key 0xF81F).
"""
import sys
from collections import deque

import numpy as np
from PIL import Image

KEY = 0xF81F  # magenta: never appears in the art


def cutout(rgb: np.ndarray) -> np.ndarray:
    """Alpha mask: flood-fill from the border through pixels close to the paper or the shadow."""
    h, w, _ = rgb.shape
    px = rgb.astype(int)
    paper = np.median(np.concatenate([px[0], px[-1], px[:, 0], px[:, -1]]), axis=0)
    near_paper = np.abs(px - paper).sum(axis=2) < 60
    # shadow = slightly darker, warm, low-contrast version of the paper (never the dark outline)
    lum = px.sum(axis=2)
    shadow = (np.abs(px - paper).sum(axis=2) < 170) & (lum > 330) & (px[:, :, 0] >= px[:, :, 2])
    bg_like = near_paper | shadow
    seen = np.zeros((h, w), bool)
    q = deque((y, x) for y in range(h) for x in (0, w - 1)) + deque((y, x) for x in range(w) for y in (0, h - 1))
    while q:
        y, x = q.popleft()
        if 0 <= y < h and 0 <= x < w and not seen[y, x] and bg_like[y, x]:
            seen[y, x] = True
            q.extend(((y + 1, x), (y - 1, x), (y, x + 1), (y, x - 1)))
    return ~seen


def main() -> None:
    src, box, height, name = sys.argv[1], sys.argv[2], int(sys.argv[3]), sys.argv[4]
    out = sys.argv[5] if len(sys.argv) > 5 else f"src/ui/chars/{name}.h"
    img = Image.open(src).convert("RGB").crop(tuple(int(v) for v in box.split(",")))
    a = cutout(np.asarray(img))
    ys, xs = np.nonzero(a)
    img = img.crop((xs.min(), ys.min(), xs.max() + 1, ys.max() + 1))
    a = a[ys.min():ys.max() + 1, xs.min():xs.max() + 1]
    w = max(1, round(img.width * height / img.height))
    small = np.asarray(img.resize((w, height), Image.LANCZOS)).astype(int)
    alpha = np.asarray(Image.fromarray((a * 255).astype(np.uint8)).resize((w, height), Image.LANCZOS)) > 110
    r, g, b = small[..., 0] >> 3, small[..., 1] >> 2, small[..., 2] >> 3
    v = (r << 11) | (g << 5) | b
    v[v == KEY] = KEY ^ 0x0020  # keep real pixels off the key
    v[~alpha] = KEY
    rows = ",\n".join("    " + ",".join(f"0x{p:04X}" for p in row) for row in v)
    with open(out, "w", encoding="ascii", newline="\n") as f:
        f.write(f"// Generated by scripts/char_sprite.py from {src.replace(chr(92), '/').split('/')[-1]}. Do not edit.\n")
        f.write(f"#pragma once\n#include <stdint.h>\n\nnamespace maz {{\nnamespace chars {{\n\n")
        f.write(f"constexpr int {name.upper()}_W = {w}, {name.upper()}_H = {height};\n")
        f.write(f"constexpr uint16_t {name.upper()}_KEY = 0x{KEY:04X};\n")
        f.write(f"const uint16_t {name.upper()}[{w * height}] = {{\n{rows}\n}};\n\n}}  // namespace chars\n}}  // namespace maz\n")
    Image.fromarray(np.where(alpha[..., None], small, [255, 0, 255]).astype(np.uint8)).resize((w * 6, height * 6), Image.NEAREST).save(out.replace(".h", "-preview.png"))
    print(out, w, "x", height, f"{100 * alpha.mean():.0f}% opaque")


if __name__ == "__main__":
    main()
